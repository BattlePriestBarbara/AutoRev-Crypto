def render_md(doc):
    out = []
    for blk in doc:
        kind = blk[0]
        if kind in ("h1", "h2", "h3", "h4"):
            out.append("\n" + "#" * int(kind[1]) + " " + blk[1] + "\n")
        elif kind == "p":
            out.append(_md_inline(blk[1]))
        elif kind == "b":
            out.append("> " + _md_inline(blk[1]))
        elif kind == "ul":
            out.extend("- " + _md_inline(x) for x in blk[1])
        elif kind == "ol":
            out.extend("%d. %s" % (n + 1, _md_inline(x))
                       for n, x in enumerate(blk[1]))
        elif kind == "table":
            out.append(_md_table(blk[1], blk[2]))
        elif kind == "code":
            out.append("```\n" + blk[1] + "\n```")
        elif kind == "note":
            out.append("> **说明：** " + _md_inline(blk[1]))
        elif kind == "red":
            out.append("> **红线：** " + _md_inline(blk[1]))
        elif kind == "hr":
            out.append("\n---\n")
        else:
            raise ValueError("unknown block: %r" % (kind,))
    return "\n".join(out) + "\n"


def render_html(doc):
    out = [_HTML_HEAD % REPORT_NO]
    for blk in doc:
        kind = blk[0]
        if kind in ("h1", "h2", "h3", "h4"):
            out.append("<%s>%s</%s>" % (kind, _html_inline(blk[1]), kind))
        elif kind == "p":
            out.append("<p>" + _html_inline(blk[1]) + "</p>")
        elif kind == "b":
            out.append('<p style="margin-left:14pt"><b>&#183;</b> '
                       + _html_inline(blk[1]) + "</p>")
        elif kind == "ul":
            out.append("<ul>")
            out.extend("<li>" + _html_inline(x) + "</li>" for x in blk[1])
            out.append("</ul>")
        elif kind == "ol":
            out.append("<ol>")
            out.extend("<li>" + _html_inline(x) + "</li>" for x in blk[1])
            out.append("</ol>")
        elif kind == "table":
            out.append("<table>")
            if blk[1]:
                out.append("<tr>" + "".join("<th>" + _html_inline(c) + "</th>"
                                            for c in blk[1]) + "</tr>")
            for r in blk[2]:
                out.append("<tr>" + "".join("<td>" + _html_inline(c) + "</td>"
                                            for c in r) + "</tr>")
            out.append("</table>")
        elif kind == "code":
            out.append("<pre>" + _esc(blk[1]) + "</pre>")
        elif kind == "note":
            out.append('<table style="width:100%"><tr><td bgcolor="#FFF2CC">'
                       '<b>说明：</b>' + _html_inline(blk[1])
                       + "</td></tr></table>")
        elif kind == "red":
            out.append('<table style="width:100%"><tr><td bgcolor="#FCE4E4">'
                       '<b>红线：</b>' + _html_inline(blk[1])
                       + "</td></tr></table>")
        elif kind == "hr":
            out.append('<div class="hr"></div>')
        else:
            raise ValueError("unknown block: %r" % (kind,))
    out.append("</body></html>\n")
    return "\n".join(out)


def write_all(doc):
    if not os.path.isdir(DOCS):
        os.makedirs(DOCS)
    for path, text in ((MD_PATH, render_md(doc)), (HTML_PATH, render_html(doc))):
        tmp = path + ".tmp"
        with io.open(tmp, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        if os.path.exists(path):
            os.remove(path)
        os.rename(tmp, path)
        print("written : %s (%d bytes)" % (path, os.path.getsize(path)))


