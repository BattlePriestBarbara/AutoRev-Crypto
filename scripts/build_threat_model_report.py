def _md_inline(s):
    """Markdown 输出：内容源本身已是 Markdown，直接原样输出即可。

    早期版本在这里把 **粗体** 转成了 <b> 标签，导致正文里混入 HTML、
    与表格单元格（保持 Markdown）不一致，故改为直通。
    """
    return s


def _esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def _html_inline(s):
    out = []
    i = 0
    while i < len(s):
        if s.startswith("**", i):
            j = s.find("**", i + 2)
            if j > 0:
                out.append("<b>" + _esc(s[i + 2:j]) + "</b>")
                i = j + 2
                continue
        if s[i] == "`":
            j = s.find("`", i + 1)
            if j > 0:
                out.append("<code>" + _esc(s[i + 1:j]) + "</code>")
                i = j + 1
                continue
        out.append(_esc(s[i]))
        i += 1
    return "".join(out)


