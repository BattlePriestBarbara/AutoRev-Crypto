def _md_table(header, rows):
    lines = []
    ncol = len(header) if header else len(rows[0])
    if header:
        lines.append("| " + " | ".join(header) + " |")
        lines.append("|" + "|".join([" --- "] * ncol) + "|")
    for r in rows:
        cells = [c.replace("|", "\\|").replace("\n", "<br>") for c in r]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


