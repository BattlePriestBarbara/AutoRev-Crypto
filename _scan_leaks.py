#!/usr/bin/env python3
"""Redaction scanner: does a public artefact still carry a private identifier?

Two modes, one pattern file:

    # scan the whole tree and write a Markdown audit
    python _scan_leaks.py --root . --report SANITIZATION_AUDIT.md

    # gate a single file (used by _check_readme.py --fail-on-leak)
    python _scan_leaks.py README.md

Design note, and the reason this file looks the way it does: patterns are loaded
from an EXTERNAL file (`_leak_patterns.txt`) rather than hard-coded here. A
redaction checker that embeds the identifiers it checks for leaks them the moment
the checker is published. The shipped template (`_leak_patterns.example.txt`)
documents the shape of every rule and carries no real value.

An absent pattern file is not an error: the scan becomes a no-op, which is the
right behaviour for a contributor without access to the real identifiers.

    pattern file format:   <label>|<python-regex>      ('#' starts a comment)

Exit codes: 0 = no finding, 1 = at least one finding, 2 = usage error.
"""
from __future__ import annotations

import argparse
import os
import re
import sys

DEFAULT_PATTERNS = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "_leak_patterns.txt")

# Text extensions worth scanning; binaries are skipped rather than decoded.
TEXT_EXTENSIONS = {
    ".py", ".js", ".mjs", ".ts", ".java", ".xml", ".md", ".txt", ".ps1", ".psm1",
    ".json", ".yml", ".yaml", ".html", ".css", ".c", ".h", ".cpp", ".gradle", ".properties",
}
SKIP_DIRECTORIES = {"__pycache__", ".git", "target", "node_modules", ".venv", "venv",
                    "maven", "m2repo"}
SKIP_FILES = {"SANITIZATION_AUDIT.md", "_leak_patterns.txt"}


def load_patterns(path: str) -> list[tuple[str, re.Pattern[str]]]:
    """Parse ``<label>|<regex>`` lines. Absent file -> empty list, not an error."""
    if not os.path.isfile(path):
        return []
    patterns: list[tuple[str, re.Pattern[str]]] = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line or line.startswith("#") or "|" not in line:
                continue
            label, _, body = line.partition("|")
            try:
                patterns.append((label.strip(), re.compile(body)))
            except re.error as error:  # a broken rule must not abort the scan
                print(f"[_scan_leaks] ignoring malformed rule {label!r}: {error}",
                      file=sys.stderr)
    return patterns


def iter_files(root: str) -> list[str]:
    found: list[str] = []
    for directory, subdirectories, names in os.walk(root):
        subdirectories[:] = [d for d in subdirectories if d not in SKIP_DIRECTORIES]
        for name in names:
            if name in SKIP_FILES:
                continue
            path = os.path.join(directory, name)
            if os.path.splitext(name)[1].lower() in TEXT_EXTENSIONS:
                found.append(path)
    return sorted(found)


def scan_file(path: str, patterns: list[tuple[str, re.Pattern[str]]]) -> list[dict]:
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            text = handle.read()
    except OSError:
        return []
    findings: list[dict] = []
    for label, pattern in patterns:
        hits = list(pattern.finditer(text))
        if not hits:
            continue
        lines = sorted({text.count("\n", 0, hit.start()) + 1 for hit in hits})
        findings.append({"label": label, "count": len(hits), "lines": lines})
    return findings


def write_report(root: str, patterns: list[tuple[str, re.Pattern[str]]],
                 per_file: dict[str, list[dict]]) -> None:
    total = sum(item["count"] for findings in per_file.values() for item in findings)
    print("# Sanitization audit\n")
    print(f"Generated by `_scan_leaks.py` against the pattern file "
          f"({len(patterns)} rules, {len(per_file)} file(s) with findings, "
          f"{total} total matches).\n")
    print("This file lists where a **private identifier still survives in a file intended for "
          "public release**. It exists so the redaction can be done deliberately, one file at a "
          "time, instead of being assumed.\n")
    print("> The patterns themselves are **not** reproduced here. A redaction report that quotes "
          "the secrets it is redacting is self-defeating, so only rule *labels* appear below.\n")
    print("> A finding is not automatically a defect. Several rules are expected to match "
          "standards data (published KAT vectors) or the publication's own rename mapping. "
          "Each entry must be judged, not blanket-fixed.\n")
    for path in sorted(per_file):
        print(f"## `{os.path.relpath(path, root)}`\n")
        print("| Rule | Matches | Lines |")
        print("| --- | --- | --- |")
        for item in sorted(per_file[path], key=lambda entry: entry["label"]):
            lines = ", ".join(str(n) for n in item["lines"][:12])
            if len(item["lines"]) > 12:
                lines += f", … (+{len(item['lines']) - 12})"
            print(f"| `{item['label']}` | {item['count']} | {lines} |")
        print()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("path", nargs="?", default=None,
                        help="a single file to gate (omit when using --root)")
    parser.add_argument("--root", default=None, help="scan a whole tree")
    parser.add_argument("--patterns", default=DEFAULT_PATTERNS, help="pattern file")
    parser.add_argument("--report", default=None, help="write a Markdown audit here")
    args = parser.parse_args(argv)

    patterns = load_patterns(args.patterns)
    if not patterns:
        print(f"[_scan_leaks] no patterns loaded from {args.patterns}; scan is a no-op")
        if args.report:
            with open(args.report, "w", encoding="utf-8") as handle:
                handle.write("# Sanitization audit\n\nNo pattern file was available, so no "
                             "redaction rule could be evaluated. This is a **no-op result, not a "
                             "clean bill of health**.\n")
        return 0

    if args.root:
        per_file: dict[str, list[dict]] = {}
        for path in iter_files(os.path.abspath(args.root)):
            findings = scan_file(path, patterns)
            if findings:
                per_file[path] = findings
        if args.report:
            with open(args.report, "w", encoding="utf-8") as handle:
                original, sys.stdout = sys.stdout, handle
                try:
                    write_report(os.path.abspath(args.root), patterns, per_file)
                finally:
                    sys.stdout = original
        total = sum(item["count"] for findings in per_file.values() for item in findings)
        print(f"[_scan_leaks] {len(per_file)} file(s) with findings, {total} matches")
        for path in sorted(per_file):
            print(f"  {os.path.relpath(path, args.root)}")
        return 1 if per_file else 0

    if args.path:
        findings = scan_file(os.path.abspath(args.path), patterns)
        for item in findings:
            print(f"leak  {item['label']} x{item['count']} "
                  f"at line(s) {', '.join(str(n) for n in item['lines'][:12])}")
        return 1 if findings else 0

    parser.error("pass a file to gate, or --root to scan a tree")
    return 2


if __name__ == "__main__":
    sys.exit(main())

